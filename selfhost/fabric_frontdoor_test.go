package selfhost

// fabric_frontdoor.fct — the transparent front door in fct — against the real
// Rust front door (fabric-facetql's frontdoor.rs/proxy.rs).
//
// Two kinds of check:
//
//   - The pure decisions (answers_agree, the routing-failure table, the
//     credential, Backend::new, resolve_once, frame_end, hop-by-hop headers),
//     one input at a time: answers_agree's verdicts come from
//     testdata/frontdoor/rust_transcript.jsonl, printed by the real crate
//     (/tmp/claude-1000/team5/frontdoor/rust — a scratch binary linking
//     fabric-facetql by path, run over testdata/frontdoor/agree.json); the rest
//     port the Rust unit tests input for input.
//
//   - The server, live: for every scenario in testdata/frontdoor/scenarios.json
//     (tests/front_door.rs, test for test, plus the rest of the status table,
//     hop-by-hop headers and the body limit), the fct door runs as a real
//     daemon on a real port in front of two FacetQL-shaped Go servers, routing
//     driven by the ported table/migration/replication, and every response and
//     every request each backend saw must equal what the same step produced
//     through the Rust FrontDoor (the transcript, generated by the same scratch
//     binary over the same scenario file). Backend base URLs are normalized to
//     {a}/{b}; a transport error's own wording (reqwest's vs the fct runtime's)
//     is compared up to "did not answer: ".

